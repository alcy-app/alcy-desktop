export type { MessageKey }

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string

export function createTranslator(language: string): Translate {
  const messages = language.toLowerCase().startsWith('pt') ? ptBR : en
  return (key, params) =>
    messages[key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      params && name in params ? String(params[name]) : placeholder,
    )
}

export const t: Translate = createTranslator(typeof navigator === 'undefined' ? 'en' : navigator.language)
